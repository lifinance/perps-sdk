#!/usr/bin/env node
// Emit Go's vendored `wasm_exec.js` inside a lazy runtime initializer.
//
// Usage: node scripts/generate-wasm-exec.mjs

import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'
import { SCRIPT_TEXT_EVALUATION } from './lib/script-text-evaluation.js'

const packageRoot = dirname(dirname(fileURLToPath(import.meta.url)))
const sourcePath = join(packageRoot, 'wasm', 'wasm_exec.js')
const outputPath = join(
  packageRoot,
  'src',
  'signers',
  'generated',
  'wasmExecRuntime.ts'
)

const source = readFileSync(sourcePath, 'utf8')

// The source ships verbatim, so a Go toolchain that reintroduces script-text
// evaluation must stop here rather than reach the emitted module.
const evaluation = SCRIPT_TEXT_EVALUATION.exec(source)
if (evaluation) {
  console.error(
    `generate-wasm-exec: ${sourcePath} evaluates script text (${evaluation[0]}), which a CSP without 'unsafe-eval' blocks`
  )
  process.exit(1)
}

// The source is Go-authored JavaScript that the TypeScript checker cannot type;
// it stays verbatim, so the whole file opts out of checking.
const header = `// @ts-nocheck
// Generated by scripts/generate-wasm-exec.mjs from wasm/wasm_exec.js.
// Do not edit: regenerate after vendoring a new Go-built signer runtime.

/** Initializes Go's runtime when the signer loads, not when the package imports. */
export function createGoRuntime(): {
  importObject: WebAssembly.Imports
  run(instance: WebAssembly.Instance): Promise<void>
} {
`

const footer = `
  return new globalThis.Go()
}
`

mkdirSync(dirname(outputPath), { recursive: true })
writeFileSync(outputPath, header + source + footer)

const emitted = readFileSync(outputPath, 'utf8')
if (emitted !== header + source + footer) {
  console.error(
    `generate-wasm-exec: ${outputPath} does not carry ${sourcePath} verbatim`
  )
  process.exit(1)
}

const previousGo = globalThis.Go
const { createGoRuntime } = await import(pathToFileURL(outputPath).href)
if (globalThis.Go !== previousGo) {
  console.error('generate-wasm-exec: importing the module initialized Go')
  process.exit(1)
}
const go = createGoRuntime()
if (typeof go.importObject !== 'object' || typeof go.run !== 'function') {
  console.error('generate-wasm-exec: initializer did not return a Go runtime')
  process.exit(1)
}

console.error(
  `generate-wasm-exec: ${outputPath} carries ${source.length} bytes of wasm_exec.js verbatim and initializes Go lazily`
)
