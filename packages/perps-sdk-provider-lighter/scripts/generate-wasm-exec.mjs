#!/usr/bin/env node
// Capture Go's vendored `wasm_exec.js` as generated TypeScript text data, then
// verify the emitted module reproduces the source exactly.
//
// The Go runtime is never imported as JavaScript: consumer bundlers must not
// parse or transform it (it references require/process/fs and breaks under
// Vite/webpack), and it must not be fetched at runtime either. Packaging it as
// an opaque string the loader hands to `new Function` keeps it verbatim.
//
// Usage: node scripts/generate-wasm-exec.mjs

import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'

const packageRoot = dirname(dirname(fileURLToPath(import.meta.url)))
const sourcePath = join(packageRoot, 'wasm', 'wasm_exec.js')
const outputPath = join(
  packageRoot,
  'src',
  'signers',
  'generated',
  'wasmExecRuntime.ts'
)

const source = readFileSync(sourcePath, 'utf8')

const body = source
  .split('\n')
  .map((line) => `  ${JSON.stringify(line)},`)
  .join('\n')

const emitted = `// Generated by scripts/generate-wasm-exec.mjs from wasm/wasm_exec.js.
// Do not edit: regenerate after vendoring a new Go-built signer runtime.

const WASM_EXEC_LINES: readonly string[] = [
${body}
]

/**
 * Go's canonical \`wasm_exec.js\`, verbatim, as opaque runtime text. Evaluated by
 * the WASM loader to install \`globalThis.Go\`.
 *
 * @internal
 */
export const WASM_EXEC_JS: string = WASM_EXEC_LINES.join('\\n')
`

mkdirSync(dirname(outputPath), { recursive: true })
writeFileSync(outputPath, emitted)

const { WASM_EXEC_JS } = await import(pathToFileURL(outputPath).href)
if (WASM_EXEC_JS !== source) {
  console.error(
    `generate-wasm-exec: emitted runtime text does not reproduce ${sourcePath} exactly`
  )
  process.exit(1)
}

console.error(
  `generate-wasm-exec: ${outputPath} reproduces ${source.length} bytes of wasm_exec.js exactly`
)
